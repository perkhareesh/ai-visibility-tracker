import { orNotFound } from "@/server/not-found";
import Link from "next/link";
import { overrideAction } from "@/app/actions";
import { EvidenceText, SafeLink, type Mark } from "@/components/evidence";
import { CitationType, Flash, fmtDate, OriginBadge, PageHeader, Pill, Section, SENT_LABEL, SentimentPill } from "@/components/ui";
import { getProvider } from "@/lib/providers";
import { cleanExcerpt } from "@/lib/analysis/sentiment";
import { requireCtx } from "@/server/session";
import { getSnapshot } from "@/server/services/reporting";

export const metadata = { title: "Snapshot" };

const REC_LABEL: Record<string, string> = { recommended: "Recommended", listed: "Listed, not recommended", mentioned: "Mentioned only", not_recommended: "Advised against", absent: "Absent" };
type Loc = { country?: string | null; region?: string | null; city?: string | null } | null;
const locText = (l: Loc) => (l ? [l.country, l.region, l.city].filter(Boolean).join(", ") || "None" : "None");

export default async function SnapshotPage({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<{ error?: string; notice?: string }> }) {
  const ctx = await requireCtx();
  const { id } = await params;
  const sp = await searchParams;
  const d = await orNotFound(getSnapshot(ctx, id));
  const s = d.s;
  const provider = getProvider(s.provider);
  const tracked = d.mentions.find((m) => m.entityType === "tracked");
  const rivals = d.mentions.filter((m) => m.entityType === "competitor");
  const latestOverride = (f: "sentiment" | "recommendation") => d.overrides.find((o) => o.field === f);
  const sentOv = latestOverride("sentiment");
  const recOv = latestOverride("recommendation");
  const marks: Mark[] = d.mentions.flatMap((m) =>
    (m.matches as Array<{ start: number; end: number; term: string; kind: string }>).map((x) => ({
      start: x.start,
      end: x.end,
      cls: m.entityType === "tracked" ? (x.kind === "product" ? "m-product" : "m-brand") : "m-rival",
      title: `${m.entityName} (${x.kind})`,
    })),
  );
  const usage = (d.response?.usage ?? null) as Record<string, unknown> | null;
  const meta = (usage?.meta ?? {}) as { webSearchCalls?: number; modelReported?: string; toolChoice?: string };

  return (
    <>
      <PageHeader
        title={s.promptText}
        description={
          <>
            {d.brandName}, {fmtDate(s.executedAt)}, {s.provider} <code>{s.model}</code>.{" "}
            <Link className="link" href={`/runs/${s.runId}`}>Back to run</Link>
          </>
        }
        actions={<><OriginBadge origin={s.dataOrigin} />{s.status === "failed" ? <Pill tone="fail">Failed execution</Pill> : <Pill tone="ok">Immutable snapshot</Pill>}</>}
      />
      <Flash sp={sp} />
      {s.dataOrigin === "simulated" && (
        <p className="mb-5 rounded-md bg-sim-soft px-4 py-2 text-sm text-sim">This answer was generated by the demo provider. It is not a ChatGPT response.</p>
      )}

      {s.status === "failed" ? (
        <div className="panel border-fail/30 p-5">
          <h2 className="font-semibold text-fail">No answer was recorded</h2>
          <p className="mt-1 text-sm">{s.errorMessage}</p>
          <p className="mt-3 text-sm text-slate">Failed executions are excluded from every metric. Use “Retry failed” on the run to try again; the result becomes a new snapshot.</p>
        </div>
      ) : (
        <div className="grid gap-6 xl:grid-cols-[minmax(0,1fr)_340px]">
          <div className="min-w-0">
            <div className="panel p-6 sm:p-8">
              <div className="mb-4 flex flex-wrap items-center gap-3 text-xs text-slate">
                <span><mark className="rounded-sm bg-brand-soft px-1 text-brand">{d.brandName}</mark> tracked brand</span>
                <span><span className="border-b border-dashed border-rival">Competitor</span></span>
                <span><span className="border-b-2 border-dotted border-brand">Product</span></span>
                <span className="inline-flex items-center gap-1"><span className="rounded bg-official px-1 text-[10px] font-semibold text-white">1</span> official site</span>
                <span className="inline-flex items-center gap-1"><span className="rounded bg-third px-1 text-[10px] font-semibold text-white">1</span> third-party mention</span>
                <span className="inline-flex items-center gap-1"><span className="rounded bg-rival px-1 text-[10px] font-semibold text-white">1</span> competitor site</span>
              </div>
              {d.response ? <EvidenceText text={d.response.responseText} marks={marks} cites={d.citations.map((c) => ({ start: c.startIndex, end: c.endIndex, n: c.position ?? 0, type: c.citationType, url: c.originalUrl }))} /> : <p className="text-fail">Response record missing.</p>}
              {d.response && (
                <details className="mt-6 border-t border-line pt-4 text-sm">
                  <summary className="cursor-pointer text-slate">Exact raw text as returned</summary>
                  <pre className="mt-3 max-h-96 overflow-auto whitespace-pre-wrap rounded bg-sunken p-3 text-xs">{d.response.responseText}</pre>
                </details>
              )}
            </div>

            <Section title={`Citations (${d.citations.length})`} description={s.citationsAvailable ? "In order of appearance. Original URLs are kept; normalised URLs are used for grouping." : undefined}>
              {!s.citationsAvailable ? (
                <p className="panel p-4 text-sm text-slate">This provider returned no citation metadata, so citations are marked unavailable rather than counted as zero.</p>
              ) : d.citations.length === 0 ? (
                <p className="panel p-4 text-sm text-slate">The provider returned citation metadata, but this answer cited no sources{meta.webSearchCalls === 0 ? " (the model did not search the web)" : ""}.</p>
              ) : (
                <ol className="panel divide-y divide-line">
                  {d.citations.map((c) => (
                    <li key={c.id} id={`cite-${c.position}`} className="grid grid-cols-[28px_1fr] gap-3 px-4 py-3 text-sm">
                      <span className="pt-0.5 font-semibold tabular-nums text-slate">{c.position}</span>
                      <div className="min-w-0">
                        <div className="flex flex-wrap items-center gap-2"><span className="font-medium">{c.title ?? c.domain}</span><CitationType type={c.citationType} />{c.citedEntity && c.citationType !== "other" && <span className="text-xs text-slate">{c.citedEntity}</span>}</div>
                        <SafeLink href={c.originalUrl}>{c.originalUrl}</SafeLink>
                        {c.normalizedUrl !== c.originalUrl && <div className="text-xs text-slate">Normalised: {c.normalizedUrl}</div>}
                      </div>
                    </li>
                  ))}
                </ol>
              )}
            </Section>
          </div>

          <aside className="space-y-6">
            <div className="panel p-4 text-sm">
              <h2 className="mb-3 font-semibold">Brand presence</h2>
              {tracked ? (
                <dl className="grid grid-cols-[1fr_auto] gap-y-1.5">
                  <dt className="text-slate">Mentioned by name</dt><dd>{tracked.mentioned ? `Yes, ${tracked.mentionCount}×` : "No"}</dd>
                  <dt className="text-slate">In a list or comparison</dt><dd>{tracked.inList ? `Yes${tracked.listRank ? `, #${tracked.listRank}` : ""}` : "No"}</dd>
                  <dt className="text-slate">Explicitly recommended</dt><dd>{tracked.recommended ? "Yes" : "No"}</dd>
                  <dt className="text-slate">Via product or service</dt><dd>{tracked.viaProduct ? tracked.productTerms.join(", ") : "No"}</dd>
                  <dt className="text-slate">Official site cited</dt><dd>{tracked.linkedViaCitation ? "Yes" : s.citationsAvailable ? "No" : "Unknown"}</dd>
                  <dt className="text-slate">Overall</dt>
                  <dd>{tracked.mentioned || tracked.viaProduct || tracked.linkedViaCitation ? <Pill tone="brand">Present</Pill> : <Pill>Absent</Pill>}</dd>
                </dl>
              ) : (
                <p className="text-slate">Analysis did not complete for this snapshot. {s.errorMessage}</p>
              )}
            </div>

            {rivals.length > 0 && (
              <div className="panel p-4 text-sm">
                <h2 className="mb-3 font-semibold">Competitors</h2>
                <ul className="space-y-1.5">
                  {rivals.map((r) => (
                    <li key={r.id} className="flex justify-between gap-2">
                      <span>{r.entityName}</span>
                      <span className="text-slate">{r.mentioned ? `${r.inList && r.listRank ? `#${r.listRank}` : "mentioned"}${r.recommended ? ", recommended" : ""}` : "absent"}</span>
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {d.sentiment && (
              <div className="panel p-4 text-sm">
                <h2 className="mb-1 font-semibold">How the answer portrays the brand</h2>
                <p className="mb-3 text-xs text-slate">Analyzer {d.sentiment.analysisVersion}. Confidence is a heuristic score{d.sentiment.confidence != null ? ` (${d.sentiment.confidence})` : ""}, not a probability.</p>
                <div className="mb-2 flex items-center gap-2"><SentimentPill label={sentOv?.value ?? d.sentiment.label} />{sentOv && <span className="text-xs text-slate">corrected from {SENT_LABEL[d.sentiment.label]}</span>}</div>
                <div className="mb-3 text-sm">{REC_LABEL[recOv?.value ?? d.sentiment.recommendationStatus]}{recOv && <span className="text-xs text-slate"> (corrected from {REC_LABEL[d.sentiment.recommendationStatus]})</span>}</div>
                <p className="text-slate">{d.sentiment.explanation}</p>
                {(d.sentiment.positives as string[]).length > 0 && <Quotes title="Positive statements" items={d.sentiment.positives as string[]} />}
                {(d.sentiment.negatives as string[]).length > 0 && <Quotes title="Negative statements" items={d.sentiment.negatives as string[]} />}
                {(d.sentiment.competitorComparisons as string[]).length > 0 && <Quotes title="Competitor comparisons" items={d.sentiment.competitorComparisons as string[]} />}
                {(d.sentiment.attributes as string[]).length > 0 && <p className="mt-3 text-xs text-slate">Attributes: {(d.sentiment.attributes as string[]).join(", ")}</p>}

                <details className="mt-4 border-t border-line pt-3">
                  <summary className="cursor-pointer font-medium">Correct a label</summary>
                  <p className="mt-2 text-xs text-slate">Corrections are stored alongside the original analysis, which stays unchanged. Metrics use the latest correction.</p>
                  {(["sentiment", "recommendation"] as const).map((field) => (
                    <form key={field} action={overrideAction} className="mt-3 space-y-2">
                      <input type="hidden" name="snapshotId" value={s.id} />
                      <input type="hidden" name="field" value={field} />
                      <label className="label text-xs" htmlFor={`v-${field}`}>{field === "sentiment" ? "Sentiment" : "Recommendation"}</label>
                      <div className="flex gap-2">
                        <select id={`v-${field}`} name="value" className="field" defaultValue={field === "sentiment" ? sentOv?.value ?? d.sentiment.label : recOv?.value ?? d.sentiment.recommendationStatus}>
                          {Object.entries(field === "sentiment" ? SENT_LABEL : REC_LABEL).map(([k, v]) => <option key={k} value={k}>{v}</option>)}
                        </select>
                        <button className="btn-secondary">Save</button>
                      </div>
                      <input name="note" className="field" placeholder="Reason (optional)" maxLength={500} />
                    </form>
                  ))}
                  {d.overrides.length > 0 && (
                    <ul className="mt-3 space-y-1 text-xs text-slate">
                      {d.overrides.map((o) => <li key={o.id}>{fmtDate(o.createdAt)}: {o.field} → {o.value}{o.note ? ` (${o.note})` : ""}</li>)}
                    </ul>
                  )}
                </details>
              </div>
            )}

            <div className="panel p-4 text-sm">
              <h2 className="mb-3 font-semibold">Location and language</h2>
              <dl className="space-y-2">
                <div><dt className="text-slate">Requested</dt><dd>{locText(s.requestedLocation as Loc)}, language {s.language}</dd></div>
                <div><dt className="text-slate">Sent to provider</dt><dd>{s.sentLocation ? locText(s.sentLocation as Loc) + " (approximate hint)" : "Nothing sent (stored as a label only)"}</dd></div>
                <div><dt className="text-slate">Reported by provider</dt><dd>{s.providerReportedLocation ? JSON.stringify(s.providerReportedLocation) : "Not reported. Localisation is unverified."}</dd></div>
              </dl>
              {provider && <p className="mt-3 text-xs text-slate">{provider.label}: country {provider.capabilities.geo.country.replace(/_/g, " ")}, region {provider.capabilities.geo.region.replace(/_/g, " ")}, city {provider.capabilities.geo.city.replace(/_/g, " ")}.</p>}
            </div>

            <div className="panel p-4 text-sm">
              <h2 className="mb-3 font-semibold">Execution metadata</h2>
              <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1.5 text-xs">
                <dt className="text-slate">Snapshot id</dt><dd className="break-all">{s.id}</dd>
                <dt className="text-slate">Response id</dt><dd className="break-all">{d.response?.providerResponseId ?? "–"}</dd>
                <dt className="text-slate">Model reported</dt><dd>{meta.modelReported ?? "–"}</dd>
                <dt className="text-slate">Web searches</dt><dd>{meta.webSearchCalls ?? "–"}</dd>
                <dt className="text-slate">Latency</dt><dd>{d.response?.latencyMs != null ? `${d.response.latencyMs} ms` : "–"}</dd>
                <dt className="text-slate">Attempt</dt><dd>{s.attempt}</dd>
                <dt className="text-slate">Usage</dt><dd className="break-all">{usage ? JSON.stringify(Object.fromEntries(Object.entries(usage).filter(([k]) => k !== "meta"))) : "–"}</dd>
                <dt className="text-slate">Cost</dt><dd>{d.response?.costUsd ? `$${d.response.costUsd}` : "Not reported by provider"}</dd>
                <dt className="text-slate">Analysis</dt><dd>{s.analysisVersion ?? s.analysisStatus}</dd>
              </dl>
            </div>
          </aside>
        </div>
      )}
    </>
  );
}

function Quotes({ title, items }: { title: string; items: string[] }) {
  return (
    <div className="mt-3">
      <div className="text-xs font-medium text-slate">{title}</div>
      <ul className="mt-1 space-y-1.5">
        {items.map((q, i) => <li key={i} className="border-l-2 border-line-strong pl-2 font-serif text-[0.95rem] leading-snug">{cleanExcerpt(q)}</li>)}
      </ul>
    </div>
  );
}
