import Link from "next/link";
import clsx from "clsx";
import type { ReactNode } from "react";
import type { Rate } from "@/lib/metrics";

export function PageHeader({ title, description, actions }: { title: string; description?: ReactNode; actions?: ReactNode }) {
  return (
    <div className="mb-6 flex flex-wrap items-end justify-between gap-4">
      <div className="max-w-2xl">
        <h1 className="text-[1.65rem] font-semibold leading-tight tracking-[-0.01em]">{title}</h1>
        {description && <p className="mt-1.5 text-sm text-slate">{description}</p>}
      </div>
      {actions && <div className="flex flex-wrap items-center gap-2">{actions}</div>}
    </div>
  );
}

export function Flash({ sp }: { sp: { error?: string; notice?: string } }) {
  if (!sp.error && !sp.notice) return null;
  return (
    <div
      role={sp.error ? "alert" : "status"}
      className={clsx(
        "mb-5 rounded-md border px-4 py-3 text-sm",
        sp.error ? "border-fail/30 bg-fail-soft text-fail" : "border-official/30 bg-official-soft text-official",
      )}
    >
      {sp.error ?? sp.notice}
    </div>
  );
}

export function Pill({ tone = "neutral", children, title }: { tone?: "neutral" | "brand" | "rival" | "official" | "third" | "fail" | "sim" | "ok"; children: ReactNode; title?: string }) {
  const tones: Record<string, string> = {
    neutral: "bg-sunken text-slate",
    brand: "bg-brand-soft text-brand",
    rival: "bg-rival-soft text-rival",
    official: "bg-official-soft text-official",
    third: "bg-third-soft text-third",
    fail: "bg-fail-soft text-fail",
    sim: "bg-sim-soft text-sim",
    ok: "bg-official-soft text-official",
  };
  return (
    <span title={title} className={clsx("inline-flex items-center whitespace-nowrap rounded px-1.5 py-0.5 text-xs font-medium", tones[tone])}>
      {children}
    </span>
  );
}

export function OriginBadge({ origin }: { origin: "live" | "simulated" }) {
  return origin === "simulated" ? (
    <Pill tone="sim" title="Generated by the demo provider. Not a real AI answer.">Simulated</Pill>
  ) : (
    <Pill tone="brand" title="Returned by a real provider API at the time shown">Live</Pill>
  );
}

const RUN_TONES = { queued: "neutral", running: "brand", completed: "ok", partial: "third", failed: "fail", cancelled: "neutral" } as const;
export function RunStatus({ status }: { status: keyof typeof RUN_TONES }) {
  return <Pill tone={RUN_TONES[status]}>{status === "partial" ? "partly failed" : status}</Pill>;
}

export const CITATION_LABEL: Record<string, string> = {
  official: "Official domain",
  third_party_mention: "Third-party mention",
  competitor: "Competitor domain",
  other: "Other source",
};
const CITATION_TONE = { official: "official", third_party_mention: "third", competitor: "rival", other: "neutral" } as const;
export function CitationType({ type }: { type: string }) {
  return <Pill tone={CITATION_TONE[type as keyof typeof CITATION_TONE] ?? "neutral"}>{CITATION_LABEL[type] ?? type}</Pill>;
}

const SENT_TONE = { positive: "ok", neutral: "neutral", negative: "fail", mixed: "third", insufficient: "neutral" } as const;
export const SENT_LABEL: Record<string, string> = { positive: "Positive", neutral: "Neutral", negative: "Negative", mixed: "Mixed", insufficient: "Not enough evidence" };
export function SentimentPill({ label }: { label: string | null | undefined }) {
  if (!label) return <span className="text-mute">–</span>;
  return <Pill tone={SENT_TONE[label as keyof typeof SENT_TONE] ?? "neutral"}>{SENT_LABEL[label] ?? label}</Pill>;
}

export function fmtRate(r: Rate | number | null | undefined) {
  const v = typeof r === "number" || r == null ? r : r.value;
  return v == null ? "No data" : `${v.toFixed(v % 1 === 0 ? 0 : 1)}%`;
}

export function fmtPp(v: number | null) {
  if (v == null) return "n/a";
  if (v === 0) return "±0 pp";
  return `${v > 0 ? "+" : "−"}${Math.abs(v).toFixed(1)} pp`;
}

export function fmtDelta(v: number | null) {
  if (v == null) return "n/a";
  return v === 0 ? "±0" : `${v > 0 ? "+" : "−"}${Math.abs(v)}`;
}

export function fmtDate(d: Date | string | null | undefined, withTime = true) {
  if (!d) return "–";
  const date = typeof d === "string" ? new Date(d) : d;
  const s = date.toLocaleString("en-GB", {
    day: "numeric",
    month: "short",
    year: "numeric",
    ...(withTime ? { hour: "2-digit", minute: "2-digit", hourCycle: "h23" } : {}),
    timeZone: "UTC",
  });
  return withTime ? `${s} UTC` : s;
}

/** A metric that links to the executions behind it. */
export function Metric({ label, value, detail, href, tone = "ink" }: { label: string; value: string; detail?: ReactNode; href?: string; tone?: "ink" | "brand" | "official" | "fail" }) {
  const body = (
    <>
      <div className="text-sm text-slate">{label}</div>
      <div className={clsx("mt-1 text-[1.9rem] font-semibold leading-none tracking-tight", { "text-brand": tone === "brand", "text-official": tone === "official", "text-fail": tone === "fail" })}>{value}</div>
      {detail && <div className="mt-2 text-xs text-slate">{detail}</div>}
    </>
  );
  return href ? (
    <Link href={href} className="panel block p-4 hover:border-ink">
      {body}
    </Link>
  ) : (
    <div className="panel p-4">{body}</div>
  );
}

export function Empty({ title, children, action }: { title: string; children?: ReactNode; action?: ReactNode }) {
  return (
    <div className="rounded-lg border border-dashed border-line-strong bg-surface px-6 py-10 text-center">
      <p className="font-medium">{title}</p>
      {children && <div className="mx-auto mt-1.5 max-w-md text-sm text-slate">{children}</div>}
      {action && <div className="mt-4 flex justify-center gap-2">{action}</div>}
    </div>
  );
}

export function Pagination({ page, pageSize, total, base }: { page: number; pageSize: number; total: number; base: Record<string, string | undefined> }) {
  const pages = Math.max(1, Math.ceil(total / pageSize));
  if (pages <= 1) return <p className="mt-3 text-xs text-slate">{total} total</p>;
  const href = (p: number) => {
    const q = new URLSearchParams(Object.entries(base).filter((e): e is [string, string] => !!e[1]));
    q.set("page", String(p));
    return `?${q.toString()}`;
  };
  return (
    <nav className="mt-3 flex items-center justify-between text-sm" aria-label="Pagination">
      <span className="text-xs text-slate">
        Page {page} of {pages}, {total} total
      </span>
      <div className="flex gap-2">
        {page > 1 && <Link className="btn-secondary" href={href(page - 1)}>Previous</Link>}
        {page < pages && <Link className="btn-secondary" href={href(page + 1)}>Next</Link>}
      </div>
    </nav>
  );
}

export function Section({ title, description, children, actions }: { title: string; description?: ReactNode; children: ReactNode; actions?: ReactNode }) {
  return (
    <section className="mb-8">
      <div className="mb-3 flex flex-wrap items-end justify-between gap-2">
        <div>
          <h2 className="text-base font-semibold">{title}</h2>
          {description && <p className="mt-0.5 text-sm text-slate">{description}</p>}
        </div>
        {actions}
      </div>
      {children}
    </section>
  );
}
